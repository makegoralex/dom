const formatArea = (value: string) => `${value.replace('.', ',')} м²`;
const formatPrice = (area: string, kind: GasblockProjectKind) => {
  const ratePerSquareMetre = kind === 'one' ? 6_500_000 / 120 : 5_500_000 / 120;
  const estimate = Math.ceil(Number(area) * ratePerSquareMetre / 100_000) * 100_000;
  return `от ${estimate.toLocaleString('ru-RU').replace(/\u00a0/g, ' ')} ₽`;
};

const makeCatalogProject = (spec: ProjectSpec, kind: GasblockProjectKind): GasblockCatalogProject => {
  const [code, totalArea, livingArea, footprint, facade, foundation, roof] = spec;
  const floorLabel = kind === 'one' ? 'Одноэтажный' : kind === 'two' ? 'Двухэтажный' : 'С мансардой';
  const floors = kind === 'one' ? '1 этаж' : kind === 'two' ? '2 этажа' : '1 этаж + мансарда';
  const profileLabel = kind === 'one' ? 'одноэтажный дом' : kind === 'two' ? 'двухэтажный дом' : 'дом с мансардой';
  const photo = kind === 'one' ? 'gasblock-single' : kind === 'two' ? 'gasblock-two-story' : 'gasblock-mansard';
  const livingText = livingArea ? `Жилая площадь — ${formatArea(livingArea)}. ` : '';
  const footprintText = footprint ? `Площадь застройки в каталоге — ${formatArea(footprint)}. ` : '';
  return {
    id: `catalog-gas-${kind}-${code.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    title: `${floorLabel} газобетонный дом №${code}`,
    shortDescription: `${floorLabel} проект дома из газобетона №${code}, общая площадь ${formatArea(totalArea)}. ${livingText}Планировку можно адаптировать под участок и состав семьи.`,
    fullDescription: `Каталожная архитектурная основа №${code}: ${profileLabel} из газобетона общей площадью ${formatArea(totalArea)}. ${livingText}${footprintText}В исходном описании проекта указаны фасад «${facade}», фундамент «${foundation}» и кровля «${roof}». Эти характеристики служат отправной точкой для обсуждения, а не готовой рабочей документацией: конструктив и фундамент необходимо проверить и адаптировать под геологию, рельеф и условия участка в Пензе или Пензенской области. Для предварительной оценки Evtenia предложит базовую комплектацию с газобетонными стенами, фундаментом с ростверком, кирпичной облицовкой, кровлей из металлочерепицы, пластиковыми окнами, внутренними перегородками и черновой отделкой. Фактический состав и смета фиксируются после согласования проекта и исходных данных.`,
    coverImage: `/api/assets/projects/catalog/${photo}.webp`,
    images: [],
    area: formatArea(totalArea),
    floors,
    bedrooms: 'Состав помещений — по планировке проекта',
    priceFrom: formatPrice(totalArea, kind),
    constructionType: 'Из газобетона',
    category: 'house',
    style: `${floorLabel} проект`,
    catalogProject: true,
    projectCode: code,
    livingArea: livingArea ? formatArea(livingArea) : undefined,
    buildingFootprint: footprint ? formatArea(footprint) : undefined,
    catalogFacade: facade,
    catalogFoundation: foundation,
    catalogRoof: roof
  };
};

